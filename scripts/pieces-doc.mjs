#!/usr/bin/env node
// Generates docs/pieces.md from the template manifests.
// Usage: node scripts/pieces-doc.mjs > docs/pieces.md   (or: pnpm docs:pieces)
import { fileURLToPath } from "node:url";
import { loadTemplate } from "./lib/manifest.mjs";

const code = (s) => `\`${s}\``;

function varLine(name, spec) {
  const parts = [`${code(name)}: ${spec.prompt}`];
  if (spec.default !== undefined) parts.push(`default ${code(spec.default)}`);
  if (spec.pattern !== undefined) parts.push(`pattern ${code(spec.pattern)}`);
  return `- ${parts.join("; ")}`;
}

/**
 * @param {import("./lib/manifest.mjs").Template} t
 * @returns {string}
 */
export function piecesDoc(t) {
  const out = [
    "# Pieces",
    "",
    "Generated by `node scripts/pieces-doc.mjs > docs/pieces.md` (`pnpm docs:pieces`). Do not edit by hand.",
    "",
  ];
  const tplVars = Object.entries(t.vars ?? {});
  if (tplVars.length > 0) {
    out.push("## Template variables", "", ...tplVars.map(([n, s]) => varLine(n, s)), "");
  }
  for (const p of t.pieces.values()) {
    out.push(`## ${p.id}`, "", p.description, "");
    out.push(`- Multiple instances: ${p.multiple ? "yes" : "no"}`);
    out.push(`- Target: ${p.target === undefined ? "repo root" : code(p.target)}`);
    out.push(`- Requires: ${p.requires.length ? p.requires.map(code).join(", ") : "none"}`);
    out.push("", "Variables:", "");
    const vars = Object.entries(p.vars);
    out.push(...(vars.length ? vars.map(([n, s]) => varLine(n, s)) : ["- none"]), "");
    for (const cls of ["owned", "shared", "seed"]) {
      out.push(`Files (${cls}):`, "");
      const list = p.files[cls];
      out.push(...(list.length ? list.map((f) => `- ${code(f)}`) : ["- none"]), "");
    }
    const merges = Object.entries(p.merge);
    if (merges.length > 0) {
      out.push("Merge strategies:", "", ...merges.map(([g, s]) => `- ${code(g)}: ${s}`), "");
    }
  }
  return out.join("\n").replace(/\n+$/, "\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const t = await loadTemplate(fileURLToPath(new URL("../template", import.meta.url)));
  process.stdout.write(piecesDoc(t));
}
