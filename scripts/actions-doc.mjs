#!/usr/bin/env node
// Generates docs/actions.md: the GitHub Actions each template, piece and hull's own workflows use,
// for org action allowlists. Usage: node scripts/actions-doc.mjs > docs/actions.md (pnpm docs:actions)
import { readFile, readdir } from "node:fs/promises";
import { join, relative } from "node:path";
import { isMain } from "./lib/is-main.mjs";
import { ROOT, findUses, walk } from "./lib/actions.mjs";

const WORKFLOW = /(^|\/)\.github\/workflows\/[^/]+\.ya?ml(\.jinja)?$/;
const code = (s) => `\`${s}\``;

/** @param {string[]} files absolute @returns {Promise<Map<string, {ref: string, comment: string}>>} */
async function actionsIn(files) {
  const found = new Map();
  for (const f of files) {
    if (!WORKFLOW.test(f)) continue;
    for (const u of findUses(await readFile(f, "utf8"))) {
      if (u.ref.startsWith("./")) continue;
      const [name, ref] = u.ref.split("@");
      found.set(`${name}@${ref}`, { name, ref, comment: u.comment.replace(/^# /, "") });
    }
  }
  return new Map([...found.entries()].sort(([a], [b]) => a.localeCompare(b)));
}

const PLACEHOLDER = /^0{40}$/;
const row = (a) =>
  PLACEHOLDER.test(a.ref)
    ? `| ${code(a.name)} | placeholder, not a real pin (TODO(hoist-release)) | ${code(a.ref)} |`
    : `| ${code(a.name)} | ${a.comment} | ${code(a.ref)} |`;

function section(heading, actions) {
  const out = [heading, ""];
  if (actions.size === 0) return [...out, "- none", ""];
  out.push("| Action | Version | Commit SHA |", "| --- | --- | --- |");
  for (const a of actions.values()) out.push(row(a));
  return [...out, ""];
}

export async function actionsDoc() {
  const out = [
    "# Actions",
    "",
    "Generated by `node scripts/actions-doc.mjs > docs/actions.md` (`pnpm docs:actions`). Do not edit by hand.",
    "",
    "Every action is pinned by full commit SHA with its version in a comment; use this list for an org allowlist.",
    "Renovate (`helpers:pinGitHubActionDigests`, via `renovate/default.json`) keeps the SHAs current in generated repos.",
    "hull itself has no Renovate config: its pins (including the `.yml.jinja` files and `scripts/lib/ci-tasks.mjs`, then `pnpm gen:ci`) are bumped by hand.",
    "",
  ];
  const all = new Map();
  const sources = [];
  for (const t of ["template", "template-rust", "rigging", ".github/workflows"])
    sources.push(...(await walk(join(ROOT, t))));
  for (const [k, a] of await actionsIn(sources)) all.set(k, a);
  out.push(...section("## All actions (allowlist)", all));
  for (const t of ["template", "template-rust"]) {
    out.push(`## ${t}`, "");
    const pieces = (await readdir(join(ROOT, t, "pieces"), { withFileTypes: true }))
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort();
    for (const id of pieces)
      out.push(
        ...section(`### ${t}/${id}`, await actionsIn(await walk(join(ROOT, t, "pieces", id)))),
      );
  }
  out.push(
    "## rigging",
    "",
    ...section("### rigging", await actionsIn(await walk(join(ROOT, "rigging")))),
  );
  const hull = await walk(join(ROOT, ".github/workflows"));
  out.push("## hull's own workflows", "");
  for (const f of hull.sort())
    out.push(...section(`### ${relative(ROOT, f)}`, await actionsIn([f])));
  return out.join("\n").replace(/\n+$/, "\n");
}

if (isMain(import.meta.url)) process.stdout.write(await actionsDoc());
