#!/usr/bin/env node
// Writes docs/agents/index.md: the map of commands, packages and docs that agents load.
// Node built-ins only. Deterministic: sorted paths, no dates, "\n" endings.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const BUDGET = 8192;

const HEADER = "generated by scripts/agents-index.mjs; do not edit";
const OUT = "docs/agents/index.md";
const SKIP = new Set(["node_modules", "dist", "target", ".turbo", ".astro", ".docspack"]);
const DOCSPACK_LINE = 'library docs: `pnpm exec docspack ask "<q>" --json`';

const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const readText = (p) => readFileSync(p, "utf8");
const isDir = (p) => existsSync(p) && statSync(p).isDirectory();
const listDir = (p) => (isDir(p) ? readdirSync(p).sort(byCode) : []);

/** Workspace directories from `  - <dir>/*` lines of pnpm-workspace.yaml. */
function workspacePackages(root) {
  const file = join(root, "pnpm-workspace.yaml");
  if (!existsSync(file)) return [];
  const globs = [];
  for (const line of readText(file).split("\n")) {
    const m = line.match(/^\s+-\s+["']?([^/*"']+)\/\*["']?\s*$/);
    if (m) globs.push(m[1]);
  }
  const out = [];
  for (const g of globs) {
    for (const name of listDir(join(root, g))) {
      if (SKIP.has(name)) continue;
      const rel = `${g}/${name}`;
      if (existsSync(join(root, rel, "package.json"))) out.push(rel);
    }
  }
  return out.sort(byCode);
}

function markdownUnder(root, rel, acc) {
  for (const name of listDir(join(root, rel))) {
    if (SKIP.has(name)) continue;
    const child = `${rel}/${name}`;
    if (isDir(join(root, child))) markdownUnder(root, child, acc);
    else if (name.endsWith(".md") && child !== OUT) acc.push(child);
  }
  return acc;
}

const title = (root, rel) => {
  const m = readText(join(root, rel)).match(/^# (.+)$/m);
  return m ? m[1].trim() : rel.slice(rel.lastIndexOf("/") + 1);
};

const fence = (header, rows) => ["```text", header, ...rows, "```"].join("\n");

const depth = (row) => row.path.split("/").length;

function render(commands, packages, docs, dropped, docspack) {
  const docRows = docs.map((d) => `|${d.path}|${d.title}`);
  if (dropped > 0) docRows.push(`… ${dropped} more under docs/ (ls docs)`);
  const parts = [
    HEADER,
    "## Commands",
    fence("|script|command", commands),
    "## Packages",
    fence("|path|name|scripts", packages),
    "## Docs",
    fence("|path|title", docRows),
  ];
  if (docspack) parts.push(DOCSPACK_LINE);
  return `${parts.join("\n\n")}\n`;
}

/** Index text for the repo at `root`. */
export function buildIndex(root) {
  const rootPkg = JSON.parse(readText(join(root, "package.json")));
  const commands = Object.keys(rootPkg.scripts ?? {})
    .sort(byCode)
    .map((k) => `|${k}|${rootPkg.scripts[k]}`);
  const dirs = workspacePackages(root);
  const packages = [];
  const docs = [];
  for (const dir of dirs) {
    const pkg = JSON.parse(readText(join(root, dir, "package.json")));
    const scripts = Object.keys(pkg.scripts ?? {})
      .sort(byCode)
      .join(",");
    packages.push(`|${dir}|${pkg.name ?? dir}|${scripts}`);
    for (const f of ["AGENTS.md", "README.md"]) {
      if (existsSync(join(root, dir, f))) docs.push({ path: `${dir}/${f}` });
    }
  }
  for (const p of markdownUnder(root, "docs", [])) docs.push({ path: p });
  for (const d of docs) d.title = title(root, d.path);
  docs.sort((a, b) => byCode(a.path, b.path));
  const docspack = Boolean(rootPkg.devDependencies?.docspack);

  // Over budget: drop only docs/ rows, deepest path first (ties: reverse sort order).
  const droppable = docs
    .filter((d) => d.path.startsWith("docs/"))
    .sort((a, b) => depth(b) - depth(a) || byCode(b.path, a.path));
  let dropped = 0;
  let kept = docs;
  let out = render(commands, packages, kept, 0, docspack);
  while (Buffer.byteLength(out) > BUDGET && dropped < droppable.length) {
    dropped += 1;
    const gone = new Set(droppable.slice(0, dropped));
    kept = docs.filter((d) => !gone.has(d));
    out = render(commands, packages, kept, dropped, docspack);
  }
  return out;
}

function main(argv) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const file = join(root, OUT);
  const text = buildIndex(root);
  if (Buffer.byteLength(text) > BUDGET) {
    process.stderr.write(
      `docs/agents/index.md is over ${BUDGET} bytes: commands and packages alone exceed the budget; shorten root scripts or package scripts\n`,
    );
  }
  if (argv.includes("--check")) {
    if (!existsSync(file) || readText(file) !== text) {
      process.stderr.write("docs/agents/index.md is stale: run `pnpm agents:index`\n");
      process.exit(1);
    }
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
