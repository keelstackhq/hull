#!/usr/bin/env node
// Writes docs/agents/index.md: the map of commands, crates and docs that agents load.
// Node built-ins only (the runner's preinstalled node runs it). Deterministic: sorted paths, no
// dates, "\n" endings.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const BUDGET = 8192;

const HEADER = "generated by scripts/agents-index.mjs; do not edit";
const OUT = "docs/agents/index.md";
const SKIP = new Set(["target", "dist", ".git"]);

/** The CI steps (spec §15), in order; the same list as AGENTS.md and ci.yml. */
export const COMMANDS = [
  ["fmt", "cargo fmt --all --check"],
  ["clippy", "cargo clippy --workspace --all-targets --locked -- -D warnings"],
  ["deny", "cargo deny --locked check bans licenses sources"],
  ["test", "cargo nextest run --workspace --locked --profile ci"],
  ["doctest", "cargo test --workspace --doc --locked"],
  ["index", "node scripts/agents-index.mjs"],
];

const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const readText = (p) => readFileSync(p, "utf8");
const isDir = (p) => existsSync(p) && statSync(p).isDirectory();
const listDir = (p) => (isDir(p) ? readdirSync(p).sort(byCode) : []);

/** `name` of the `[package]` table, or null. */
function packageName(text) {
  let inside = false;
  for (const line of text.split("\n")) {
    const t = line.trim();
    if (t.startsWith("[")) inside = t === "[package]";
    else if (inside) {
      const m = t.match(/^name\s*=\s*"([^"]+)"/);
      if (m) return m[1];
    }
  }
  return null;
}

/** Crates under crates/: `{ dir, name, kinds }`, kinds from src/lib.rs and src/main.rs. */
function crates(root) {
  const out = [];
  for (const name of listDir(join(root, "crates"))) {
    const dir = `crates/${name}`;
    const manifest = join(root, dir, "Cargo.toml");
    if (SKIP.has(name) || !existsSync(manifest)) continue;
    const kinds = [];
    if (existsSync(join(root, dir, "src/lib.rs"))) kinds.push("lib");
    if (existsSync(join(root, dir, "src/main.rs"))) kinds.push("bin");
    out.push({ dir, name: packageName(readText(manifest)) ?? name, kinds: kinds.join(",") });
  }
  return out;
}

function markdownUnder(root, rel, acc) {
  for (const name of listDir(join(root, rel))) {
    if (SKIP.has(name)) continue;
    const child = `${rel}/${name}`;
    if (isDir(join(root, child))) markdownUnder(root, child, acc);
    else if (name.endsWith(".md") && child !== OUT) acc.push(child);
  }
  return acc;
}

const title = (root, rel) => {
  const m = readText(join(root, rel)).match(/^# (.+)$/m);
  return m ? m[1].trim() : rel.slice(rel.lastIndexOf("/") + 1);
};

const fence = (header, rows) => ["```text", header, ...rows, "```"].join("\n");

const depth = (row) => row.path.split("/").length;

function render(rows, docs, dropped) {
  const docRows = docs.map((d) => `|${d.path}|${d.title}`);
  if (dropped > 0) docRows.push(`… ${dropped} more under docs/ (ls docs)`);
  const parts = [
    HEADER,
    "## Commands",
    fence("|step|command", COMMANDS.map(([k, v]) => `|${k}|${v}`)),
    "## Crates",
    fence("|path|name|targets", rows),
    "## Docs",
    fence("|path|title", docRows),
  ];
  return `${parts.join("\n\n")}\n`;
}

/** Index text for the repo at `root`. */
export function buildIndex(root) {
  const rows = [];
  const docs = [];
  for (const c of crates(root)) {
    rows.push(`|${c.dir}|${c.name}|${c.kinds}`);
    for (const f of ["AGENTS.md", "README.md"]) {
      if (existsSync(join(root, c.dir, f))) docs.push({ path: `${c.dir}/${f}` });
    }
  }
  for (const p of markdownUnder(root, "docs", [])) docs.push({ path: p });
  for (const d of docs) d.title = title(root, d.path);
  docs.sort((a, b) => byCode(a.path, b.path));

  // Over budget: drop only docs/ rows, deepest path first (ties: reverse sort order).
  const droppable = docs
    .filter((d) => d.path.startsWith("docs/"))
    .sort((a, b) => depth(b) - depth(a) || byCode(b.path, a.path));
  let dropped = 0;
  let out = render(rows, docs, 0);
  while (Buffer.byteLength(out) > BUDGET && dropped < droppable.length) {
    dropped += 1;
    const gone = new Set(droppable.slice(0, dropped));
    out = render(
      rows,
      docs.filter((d) => !gone.has(d)),
      dropped,
    );
  }
  return out;
}

function main(argv) {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const file = join(root, OUT);
  const text = buildIndex(root);
  if (argv.includes("--check")) {
    if (!existsSync(file) || readText(file) !== text) {
      process.stderr.write("docs/agents/index.md is stale: run `node scripts/agents-index.mjs`\n");
      process.exit(1);
    }
    return;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2));
}
